#!/usr/bin/env python3
"""Renders cargo-about's JSON (stdin) as THIRD-PARTY-NOTICES.md (argv[1]).

Filewinch's own crates are left out (they are Filewinch, AGPL-3.0-or-later). Each distinct
licence text appears once, with every component that uses it. The app parses this file for
About > Third-Party Notices: keep the `## ` / `### ` headings and ```text fences as they are.
"""

import json
import sys

d = json.load(sys.stdin)
own = lambda c: c["name"].startswith("filewinch")

crates = sorted(
    (c["package"] for c in d["crates"] if not own(c["package"])),
    key=lambda p: (p["name"].lower(), p["version"]),
)
groups = []
for lic in d["licenses"]:
    users = sorted({(u["crate"]["name"], u["crate"]["version"]) for u in lic["used_by"] if not own(u["crate"])})
    if users:
        groups.append((lic["name"], lic["id"], users, lic["text"].strip("\n")))
groups.sort(key=lambda g: (-len(g[2]), g[1], g[2][0]))

out = []
w = out.append
w("# Third-party notices\n")
w("Filewinch (Copyright © 2026 XploreDatum Technologies LLP, licensed under the GNU AGPL v3 or")
w("later) is built on the open-source components below. Generated by `scripts/licenses.sh` from")
w("Cargo.lock for every platform Filewinch ships on; do not edit by hand.\n")
w(f"## Components ({len(crates)})\n")
w("| Component | Version | Licence |")
w("|---|---|---|")
for p in crates:
    w(f"| {p['name']} | {p['version']} | {p.get('license') or 'see text'} |")
w("")
w(f"## Licence texts ({len(groups)})\n")
for name, ident, users, text in groups:
    w(f"### {name} ({ident})\n")
    w("Used by: " + ", ".join(f"{n} {v}" for n, v in users) + ".\n")
    w("```text")
    w(text.replace("```", "'''"))
    w("```\n")
open(sys.argv[1], "w").write("\n".join(out))
print(f"{len(crates)} components, {len(groups)} licence texts")
